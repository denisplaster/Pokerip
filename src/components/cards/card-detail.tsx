"use client";

import { useQuery } from "@tanstack/react-query";
import { Coins, Heart, LoaderCircle, PackageOpen, ShoppingCart, Tag, TrendingDown, TrendingUp, Undo2, Users } from "lucide-react";
import Link from "next/link";
import { useState } from "react";
import { PriceChart } from "@/components/charts/price-chart";
import { RC } from "@/components/common/coin-icon";
import { BuyDialog, type BuyableListing } from "@/components/market/buy-dialog";
import { ListDialog } from "@/components/market/list-dialog";
import { usePublicConfig, useUser } from "@/components/providers";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { useCardActions } from "@/hooks/use-card-actions";
import { api } from "@/lib/api-client";
import { formatDate, formatPercentChange, formatProbability, timeAgo } from "@/lib/format";
import { cn } from "@/lib/utils";
import type { CardDetail as CardDetailData } from "@/server/services/cards";
import type { ListingView } from "@/server/services/marketplace";
import { PokeCard } from "./poke-card";
import { RarityBadge } from "./rarity-badge";
import { TiltCard } from "./tilt-card";

function Change({ label, value }: { label: string; value: number | null | undefined }) {
  const up = (value ?? 0) > 0;
  const down = (value ?? 0) < 0;
  return (
    <div className="rounded-lg bg-white/[0.04] px-3 py-2">
      <p className="text-[11px] uppercase tracking-wide text-muted-foreground">{label}</p>
      <p className={cn("flex items-center gap-1 text-sm font-semibold tabular", up && "text-emerald-300", down && "text-rose-300")}>
        {up ? <TrendingUp className="size-3.5" /> : down ? <TrendingDown className="size-3.5" /> : null}
        {formatPercentChange(value)}
      </p>
    </div>
  );
}

/** Full card view: artwork, fictional market data, owned copies and trading actions. */
export function CardDetailView({ initial, compact }: { initial: CardDetailData; compact?: boolean }) {
  const user = useUser();
  const { instantSellBps } = usePublicConfig();
  const actions = useCardActions();
  const { data = initial } = useQuery({
    queryKey: ["card", initial.card.id],
    queryFn: () => api<CardDetailData>(`/api/cards/${initial.card.id}`),
    initialData: initial,
    staleTime: 10_000,
  });
  const { data: listings } = useQuery({
    queryKey: ["listings", { cardId: data.card.id }],
    queryFn: () => api<{ items: ListingView[] }>(`/api/marketplace/listings?cardId=${data.card.id}&sort=price_asc&limit=8`),
  });
  const [listing, setListing] = useState<{ userCardId: string } | null>(null);
  const [buying, setBuying] = useState<BuyableListing | null>(null);
  const card = data.card;
  const owned = data.owned;
  const sellPrice = Math.max(1, Math.floor((card.currentValue * instantSellBps) / 10_000));
  const ownedFree = owned.filter((o) => o.status === "OWNED");

  return (
    <div className={cn("grid gap-8", compact ? "md:grid-cols-[240px_1fr]" : "lg:grid-cols-[minmax(260px,380px)_1fr]")}>
      <div className="space-y-4">
        <div className={cn("mx-auto", compact ? "w-56" : "w-72 sm:w-80 lg:w-full")}>
          <TiltCard max={16}>
            <PokeCard card={card} holo sizes="380px" priority />
          </TiltCard>
        </div>
        {!card.imageUrl && <p className="text-center text-[11px] text-muted-foreground">Placeholder artwork generated by RipVault.</p>}
        {user && owned.length > 0 && (
          <Button
            variant="outline"
            className="w-full"
            onClick={() => actions.favorite.mutate({ cardId: card.id, favorite: !data.isFavorite })}
            disabled={actions.favorite.isPending}
            aria-pressed={data.isFavorite}
          >
            <Heart className={cn(data.isFavorite && "fill-rose-400 text-rose-400")} /> {data.isFavorite ? "Favourited" : "Add to favourites"}
          </Button>
        )}
      </div>

      <div className="min-w-0 space-y-6">
        <div className="space-y-2">
          <div className="flex flex-wrap items-center gap-2">
            <RarityBadge rarity={card.rarity} />
            {card.grade && <Badge variant="gold">{card.grade}</Badge>}
            <Badge variant="outline" className="capitalize">{card.category.toLowerCase()}</Badge>
            {!data.isActive && <Badge variant="destructive">Retired</Badge>}
          </div>
          <h1 className={cn("font-display font-bold tracking-tight", compact ? "text-2xl" : "text-3xl sm:text-4xl")}>{card.name}</h1>
          <p className="text-sm text-muted-foreground">
            {card.variant ? `${card.variant} · ` : ""}
            {card.set.name} · {card.number} · {card.releaseYear}
          </p>
        </div>

        <div className="grid gap-3 sm:grid-cols-[1.2fr_1fr]">
          <div className="rounded-xl border bg-gradient-to-br from-amber-400/[0.08] to-transparent p-4">
            <p className="text-xs uppercase tracking-wide text-muted-foreground">Virtual value</p>
            <RC amount={card.currentValue} className="mt-1 text-3xl text-amber-100" />
            <p className="mt-1 text-xs text-muted-foreground">
              Base {data.baseValue.toLocaleString()} RC · 7d volume {data.change?.volume7d.toLocaleString() ?? 0}
            </p>
          </div>
          <div className="grid grid-cols-3 gap-2">
            <Change label="24h" value={data.change?.d1} />
            <Change label="7d" value={data.change?.d7} />
            <Change label="30d" value={data.change?.d30} />
            <div className="col-span-3 flex items-center justify-between rounded-lg bg-white/[0.04] px-3 py-2 text-xs text-muted-foreground">
              <span className="flex items-center gap-1">
                <Users className="size-3.5" /> {data.owners} collectors own this
              </span>
              <span>{data.activeListings ? `${data.activeListings} listed from ${data.lowestListing?.toLocaleString()} RC` : "No listings"}</span>
            </div>
          </div>
        </div>

        <section className="rounded-xl border p-4">
          <h2 className="mb-3 font-display font-semibold">Virtual price history</h2>
          <PriceChart history={data.history} height={compact ? 180 : 240} />
        </section>

        {user && (
          <section className="rounded-xl border p-4">
            <div className="mb-3 flex items-center justify-between gap-2">
              <h2 className="font-display font-semibold">Your copies ({owned.length})</h2>
              {ownedFree.length > 1 && (
                <Button
                  size="sm"
                  variant="outline"
                  disabled={actions.sell.isPending}
                  onClick={() => actions.sell.mutate(ownedFree.slice(1).map((o) => o.id))}
                >
                  <Coins /> Sell {ownedFree.length - 1} duplicate{ownedFree.length - 1 === 1 ? "" : "s"} · {(sellPrice * (ownedFree.length - 1)).toLocaleString()} RC
                </Button>
              )}
            </div>
            {owned.length === 0 ? (
              <p className="text-sm text-muted-foreground">You don&apos;t own this card yet. Find it in packs below or buy one on the marketplace.</p>
            ) : (
              <ul className="divide-y">
                {owned.map((o) => (
                  <li key={o.id} className="flex flex-wrap items-center justify-between gap-3 py-2.5">
                    <div className="text-sm">
                      <p className="font-medium">
                        {o.source === "PACK" ? "Pulled from a pack" : o.source === "MARKETPLACE" ? "Bought on the marketplace" : o.source === "MYSTERY_BOX" ? "Won in a mystery box" : "Granted"}
                      </p>
                      <p className="text-xs text-muted-foreground">
                        {formatDate(o.acquiredAt)} · acquired at {o.acquiredValue.toLocaleString()} RC
                      </p>
                    </div>
                    {o.status === "LISTED" && o.listing ? (
                      <div className="flex items-center gap-2">
                        <Badge variant="cyan">Listed · {o.listing.price.toLocaleString()} RC</Badge>
                        <Button size="sm" variant="ghost" disabled={actions.cancel.isPending} onClick={() => actions.cancel.mutate(o.listing!.id)}>
                          <Undo2 /> Cancel
                        </Button>
                      </div>
                    ) : (
                      <div className="flex items-center gap-2">
                        <Button size="sm" variant="outline" onClick={() => setListing({ userCardId: o.id })}>
                          <Tag /> List
                        </Button>
                        <Button size="sm" variant="gold" disabled={actions.sell.isPending} onClick={() => actions.sell.mutate([o.id])}>
                          {actions.sell.isPending ? <LoaderCircle className="animate-spin" /> : <Coins />} Sell · {sellPrice.toLocaleString()} RC
                        </Button>
                      </div>
                    )}
                  </li>
                ))}
              </ul>
            )}
            <p className="mt-2 text-[11px] text-muted-foreground">Instant sales pay {instantSellBps / 100}% of the current virtual value in Rip Coins.</p>
          </section>
        )}

        <section className="rounded-xl border p-4">
          <h2 className="mb-3 font-display font-semibold">On the marketplace</h2>
          {!listings ? (
            <LoaderCircle className="size-4 animate-spin text-muted-foreground" />
          ) : listings.items.length === 0 ? (
            <p className="text-sm text-muted-foreground">No active listings for this card.</p>
          ) : (
            <ul className="divide-y">
              {listings.items.map((l) => {
                const mine = user?.id === l.sellerId;
                return (
                  <li key={l.id} className="flex items-center justify-between gap-3 py-2.5 text-sm">
                    <div>
                      <RC amount={l.price} className="text-amber-200" />
                      <p className="text-xs text-muted-foreground">
                        by {l.seller.username} · {timeAgo(l.createdAt)}
                      </p>
                    </div>
                    {mine ? (
                      <Badge variant="outline">Your listing</Badge>
                    ) : user ? (
                      <Button size="sm" onClick={() => setBuying(l)}>
                        <ShoppingCart /> Buy
                      </Button>
                    ) : (
                      <Button size="sm" variant="outline" asChild>
                        <Link href={`/login?callbackUrl=/collection/${card.id}`}>Sign in to buy</Link>
                      </Button>
                    )}
                  </li>
                );
              })}
            </ul>
          )}
        </section>

        <div className="grid gap-4 md:grid-cols-2">
          <section className="rounded-xl border p-4">
            <h2 className="mb-3 font-display font-semibold">Available in packs</h2>
            {data.packs.length === 0 ? (
              <p className="text-sm text-muted-foreground">Not currently in any pack&apos;s drop pool.</p>
            ) : (
              <ul className="space-y-2">
                {data.packs.map((p) => (
                  <li key={p.id} className="flex items-center justify-between gap-2 text-sm">
                    <Link href={`/packs/${p.slug}`} className="font-medium hover:underline">
                      {p.name}
                    </Link>
                    <span className="flex items-center gap-2 text-xs text-muted-foreground">
                      <span className="tabular text-cyan-200" title="Chance per card slot">{formatProbability(p.slotProbability)}</span>/card ·
                      <span className="tabular">{formatProbability(p.packProbability)}</span>/pack
                      <Link href={`/open/${p.slug}`} aria-label={`Open ${p.name}`} className="text-violet-300 hover:text-violet-200">
                        <PackageOpen className="size-4" />
                      </Link>
                    </span>
                  </li>
                ))}
              </ul>
            )}
          </section>
          <section className="rounded-xl border p-4">
            <h2 className="mb-3 font-display font-semibold">Recent sales</h2>
            {data.sales.length === 0 ? (
              <p className="text-sm text-muted-foreground">No marketplace sales yet.</p>
            ) : (
              <ul className="space-y-1.5 text-sm">
                {data.sales.map((s) => (
                  <li key={s.id} className="flex items-center justify-between gap-2">
                    <RC amount={s.price} />
                    <span className="truncate text-xs text-muted-foreground">
                      {s.seller.username} → {s.buyer.username} · {timeAgo(s.createdAt)}
                    </span>
                  </li>
                ))}
              </ul>
            )}
          </section>
        </div>
      </div>

      {listing && <ListDialog open onOpenChange={(o) => !o && setListing(null)} userCardId={listing.userCardId} card={card} />}
      <BuyDialog listing={buying} onOpenChange={(o) => !o && setBuying(null)} />
    </div>
  );
}
